/**
 * Контракт одной миграции схемы storage.
 *
 * Миграция — это ЧИСТАЯ функция `(oldSettings) => newSettings`: она не трогает
 * chrome.storage, не логирует, не знает о версиях вокруг себя. Всю «грязь»
 * (чтение/запись, бэкап, бамп версии, обработку ошибок) берёт на себя Migrator.
 * Благодаря этому каждую миграцию можно протестировать как обычную функцию.
 *
 * Удаление ключа: верни объект БЕЗ этого ключа — Migrator вычислит дифф и
 * физически удалит исчезнувшие ключи из storage (так работают переименования).
 */

/** Нетипизированный снимок storage — на входе у миграции произвольная старая форма. */
export type RawSettings = Record<string, unknown>;

export interface Migration {
  /**
   * Целевая версия, которую ПРОИЗВОДИТ эта миграция. Исходная всегда `to - 1`,
   * поэтому цепочка обязана идти без дыр: 2, 3, 4, …
   */
  readonly to: number;
  /** Человекочитаемое описание — попадает в dev-лог Migrator'а. */
  readonly description: string;
  /** Чистое преобразование старого снимка настроек в новый. */
  readonly migrate: (old: RawSettings) => RawSettings;
}
